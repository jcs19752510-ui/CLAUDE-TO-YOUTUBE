RULES = [  # (정규식, 바꿀 말) — 위에서부터 차례로
 (r"(갈|할|둘|다룰|정리할)게요", lambda m: {"갈":"가겠습니다","할":"하겠습니다","둘":"두겠습니다","다룰":"다루겠습니다","정리할":"정리하겠습니다"}[m.group(1)]),
 (r"드릴게요", "드리겠습니다"), (r"거예요", "것입니다"), (r"(이에요|예요)", "입니다"), (r"아니에요", "아닙니다"),
 (r"세요", "십시오"), (r"돼요", "됩니다"), (r"모자라요", "모자랍니다"),
 (r"(있|없|좋|많|않|괜찮|같)(아|어)요", lambda m: m.group(1) + "습니다"),
 (r"쉬워요", "쉽습니다"),
 (r"([가-힣])어요", lambda m: m.group(1) + "습니다" if (ord(m.group(1)) - 0xAC00) % 28 == 20 else m.group(0)),
]
def formal(x):
    if x in FIX: return FIX[x]
    for pat, rep in RULES: x = re.sub(pat, rep, x)
    for a, b in (("이걸", "이것을"), ("뭘", "무엇을"), ("얘기", "이야기"), ("별거", "대단한 일")): x = x.replace(a, b)
    return x
